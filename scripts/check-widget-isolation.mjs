import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source = await readFile('app/widget-embed.ts','utf8');
assert.match(source, /visibility:visible|style="display:block;width:100%/);
assert.match(source, /loading="eager"/);
const code = source.slice(source.indexOf('<script>') + 8, source.indexOf('</script>'));
let marker = false;
const listeners = {};
const frame = {style:{display:'block',height:'700px'},contentWindow:{},contentDocument:{querySelector:()=>marker},addEventListener:(name,fn)=>listeners[name]=fn};
const origin = 'https://store.example';
vm.runInNewContext(code,{document:{currentScript:{previousElementSibling:frame}},window:{location:{origin},addEventListener:(name,fn)=>listeners[name]=fn}});
const send = (extra={}) => listeners.message({source:frame.contentWindow,origin,data:{type:'prana-widget-height',height:420},...extra});
assert.equal(frame.style.display,'block','Iframe remains visible if Shopify does not execute the inline script');
send(); assert.equal(frame.style.display,'block','Unmarked storefront page cannot resize the iframe');
listeners.load(); assert.equal(frame.style.display,'none','Storefront fallback is hidden');
marker=true; send({source:{}}); assert.equal(frame.style.height,'700px','Other frame cannot resize');
send({origin:'https://other.example'}); assert.equal(frame.style.height,'700px','Other origin cannot resize');
send(); assert.equal(frame.style.height,'420px'); assert.equal(frame.style.display,'block');
send({data:{type:'prana-widget-height',height:Infinity}}); assert.equal(frame.style.height,'420px');
send({data:{type:'prana-widget-height',height:0}}); assert.equal(frame.style.height,'1px'); assert.equal(frame.style.display,'none');
const runtime=(await readFile('app/storefront-quiz.js','utf8')).replaceAll('\r\n','\n');
const cleanup=runtime.slice(runtime.indexOf('    function cleanupWidget(event)'),runtime.indexOf('    document.addEventListener("shopify:section:unload"'));
let stops=0,closes=0,removes=0;
const env={removed:false,root:{},closeScanChat:()=>closes++,stopCamera:()=>stops++,removeLauncher:()=>removes++,document:{removeEventListener(){}}};
const fn=new Function('env','with(env){'+cleanup+';return cleanupWidget;}')(env);
fn({type:'shopify:section:unload',target:{contains:()=>false}});assert.equal(stops,0);
fn({type:'shopify:section:unload',target:{contains:()=>true}});assert.equal(env.removed,true);assert.equal(closes,1);assert.equal(stops,1);assert.equal(removes,1);
console.log('PASS: iframe fallback isolation, trusted resize messages, and widget removal cleanup.');
